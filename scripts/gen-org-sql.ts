import { writeFileSync } from 'node:fs';
import { ORG_SEED } from '../src/data/orgSeed';

const q = (v?: string) => (v === undefined ? 'null' : `'${v.replace(/'/g, "''")}'`);
// parents first so foreign keys resolve; the seed is already ordered that way except guided_by refs, added in a 2nd pass
const inserts = ORG_SEED.map((s, i) =>
  `  (${q(s.id)}, ${q(s.title)}, ${q(s.group ?? '')}, ${q(s.plannedName ?? '')}, ${q(s.roleSlug)}, ${q(s.parentId)}, null, ${q(s.kind ?? 'internal')}, ${(i + 1) * 10})`).join(',\n');
const guided = ORG_SEED.filter(s => s.guidedBy).map(s => `update public.org_positions set guided_by_id = ${q(s.guidedBy)} where id = ${q(s.id)} and guided_by_id is null;`).join('\n');

const sql = `-- ============================================================================
--  PestCure — signup approval + dynamic org chart   (generated by scripts/gen-org-sql.ts)
--  Paste into Supabase > SQL Editor > Run.   Requires schema.sql + users_table.sql first.
--
--  1. New sign-ups (email or Google) start as 'pending'. Only admins can approve/reject.
--     Admin emails below become admin + approved automatically when they sign up.
--  2. org_positions = SEATS (title, group, role template, reports-to, guided-by).
--     org_assignments = who holds a seat, with dates (history kept).
--  3. Accountable/approver of a person = holder of the nearest FILLED seat above theirs
--     (reports_to chain). If none is filled, the admin is accountable — admins can always act.
--  4. RLS: a pending/rejected account cannot create or read a workspace.
--
--  Idempotent. Existing sign-ups are kept and marked approved.
-- ============================================================================

begin;

-- ---- admin emails (EDIT here; add Ranjan sir's email later) -----------------
create table if not exists public.admin_emails (email text primary key);
alter table public.admin_emails enable row level security;
revoke all on public.admin_emails from anon, authenticated;
insert into public.admin_emails (email) values ('tusharbali855@gmail.com'), ('rks@pest-cure.com') on conflict do nothing;

-- ---- app_users: approval status ----------------------------------------------
alter table public.app_users add column if not exists status text not null default 'approved';
alter table public.app_users add column if not exists decided_at timestamptz;
alter table public.app_users add column if not exists decided_by uuid references auth.users(id) on delete set null;
alter table public.app_users add column if not exists reject_reason text;
alter table public.app_users drop constraint if exists app_users_status_check;
alter table public.app_users add constraint app_users_status_check check (status in ('pending','approved','rejected','inactive'));
alter table public.app_users alter column status set default 'pending';   -- existing rows stay approved; new sign-ups wait

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
declare is_adm boolean := exists (select 1 from public.admin_emails where lower(email) = lower(new.email));
begin
  insert into public.app_users (id, email, full_name, status, decided_at)
  values (new.id, new.email, coalesce(new.raw_user_meta_data->>'full_name', new.raw_user_meta_data->>'name', ''),
          case when is_adm then 'approved' else 'pending' end, case when is_adm then now() end)
  on conflict (id) do nothing;
  if is_adm then insert into public.admins (user_id) values (new.id) on conflict do nothing; end if;
  return new;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();

-- admins who already signed up
insert into public.admins (user_id) select u.id from auth.users u join public.admin_emails e on lower(e.email) = lower(u.email) on conflict do nothing;
update public.app_users set status = 'approved', decided_at = coalesce(decided_at, now())
 where id in (select user_id from public.admins) and status <> 'approved';

create or replace function public.is_approved()
returns boolean language sql stable security definer set search_path = public as $$
  select public.is_admin() or exists (select 1 from public.app_users where id = auth.uid() and status = 'approved')
$$;
grant execute on function public.is_approved() to authenticated;

-- a pending/rejected account may not create a workspace (enforced in the database, not just the UI)
drop policy if exists workspace_insert_approved on public.workspaces;
create policy workspace_insert_approved on public.workspaces as restrictive for insert to authenticated
  with check (public.is_approved());

-- ---- org chart ------------------------------------------------------------------
create table if not exists public.org_positions (
  id           text primary key,
  title        text not null,
  group_name   text not null default '',
  planned_name text not null default '',
  role_slug    text,
  parent_id    text references public.org_positions(id) on delete set null,
  guided_by_id text references public.org_positions(id) on delete set null,
  kind         text not null default 'internal' check (kind in ('internal','partner')),
  sort         integer not null default 0,
  created_at   timestamptz not null default now()
);
create table if not exists public.org_assignments (
  id          uuid primary key default gen_random_uuid(),
  position_id text not null references public.org_positions(id) on delete cascade,
  user_id     uuid not null references auth.users(id) on delete cascade,
  from_date   date not null default current_date,
  to_date     date,
  assigned_by uuid references auth.users(id) on delete set null
);
create unique index if not exists org_assignments_open_seat on public.org_assignments(position_id) where to_date is null;
create unique index if not exists org_assignments_open_user on public.org_assignments(user_id) where to_date is null;

-- a seat can never report to itself or to one of its own reports
create or replace function public.org_no_cycle() returns trigger language plpgsql as $$
begin
  if new.parent_id is null then return new; end if;
  if new.parent_id = new.id then raise exception 'A position cannot report to itself.'; end if;
  if exists (
    with recursive up as (
      select id, parent_id from public.org_positions where id = new.parent_id
      union all
      select p.id, p.parent_id from public.org_positions p join up on p.id = up.parent_id)
    select 1 from up where id = new.id
  ) then raise exception 'That reporting line would create a loop.'; end if;
  return new;
end $$;
drop trigger if exists org_positions_no_cycle on public.org_positions;
create trigger org_positions_no_cycle before insert or update of parent_id on public.org_positions
  for each row execute function public.org_no_cycle();

alter table public.org_positions   enable row level security;
alter table public.org_assignments enable row level security;
revoke all on public.org_positions, public.org_assignments from anon, authenticated;
grant select, insert, update, delete on public.org_positions to authenticated;
grant select on public.org_assignments to authenticated;
drop policy if exists org_positions_read on public.org_positions;
create policy org_positions_read on public.org_positions for select to authenticated using (public.is_approved());
drop policy if exists org_positions_admin on public.org_positions;
create policy org_positions_admin on public.org_positions for all to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists org_assignments_read on public.org_assignments;
create policy org_assignments_read on public.org_assignments for select to authenticated using (public.is_approved());

-- who is accountable for a person: holder of the nearest filled seat above theirs; NULL = the admin
create or replace function public.org_accountable(p_user uuid)
returns uuid language sql stable security definer set search_path = public as $$
  with recursive me as (
    select position_id from public.org_assignments where user_id = p_user and to_date is null),
  up as (
    select p.id, p.parent_id, 1 as depth from public.org_positions p join me on p.id = me.position_id
    union all
    select p.id, p.parent_id, up.depth + 1 from public.org_positions p join up on p.id = up.parent_id where up.depth < 30)
  select a.user_id from up
  join public.org_assignments a on a.position_id = up.parent_id and a.to_date is null
  order by up.depth limit 1
$$;
grant execute on function public.org_accountable(uuid) to authenticated;

create or replace function public._org_set_holder(p_position text, p_user uuid)
returns void language plpgsql security definer set search_path = public as $$
begin
  update public.org_assignments set to_date = current_date
   where to_date is null and (position_id = p_position or user_id = p_user);
  insert into public.org_assignments (position_id, user_id, assigned_by) values (p_position, p_user, auth.uid());
end $$;
revoke all on function public._org_set_holder(text, uuid) from public, anon, authenticated;

-- admin: approve a sign-up, optionally seat them + pick the role template in the same step
create or replace function public.approve_user(p_user uuid, p_position text default null, p_role text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_role text;
begin
  if not public.is_admin() then raise exception 'Only an admin can approve users.'; end if;
  if not exists (select 1 from public.app_users where id = p_user) then raise exception 'User not found.'; end if;
  if p_position is not null and not exists (select 1 from public.org_positions where id = p_position) then raise exception 'Position not found.'; end if;
  v_role := coalesce(p_role, (select role_slug from public.org_positions where id = p_position));
  update public.app_users set status = 'approved', decided_at = now(), decided_by = auth.uid(), reject_reason = null,
         assigned_role_slug = coalesce(v_role, assigned_role_slug),
         assigned_at = case when v_role is not null then now() else assigned_at end
   where id = p_user;
  if p_position is not null then perform public._org_set_holder(p_position, p_user); end if;
  return jsonb_build_object('role', v_role, 'position', p_position, 'accountable', public.org_accountable(p_user));
end $$;
grant execute on function public.approve_user(uuid, text, text) to authenticated;

create or replace function public.reject_user(p_user uuid, p_reason text default null)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'Only an admin can reject users.'; end if;
  if p_user in (select user_id from public.admins) then raise exception 'An admin account cannot be rejected.'; end if;
  update public.app_users set status = 'rejected', decided_at = now(), decided_by = auth.uid(), reject_reason = nullif(trim(p_reason), '') where id = p_user;
  update public.org_assignments set to_date = current_date where user_id = p_user and to_date is null;
end $$;
grant execute on function public.reject_user(uuid, text) to authenticated;

-- admin: put someone on a seat (or vacate it with a null user) — old holder keeps their history
create or replace function public.assign_holder(p_position text, p_user uuid)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'Only an admin can change who holds a seat.'; end if;
  if not exists (select 1 from public.org_positions where id = p_position) then raise exception 'Position not found.'; end if;
  if p_user is null then
    update public.org_assignments set to_date = current_date where position_id = p_position and to_date is null;
  else
    if not exists (select 1 from public.app_users where id = p_user and status = 'approved') then raise exception 'Only approved users can hold a seat.'; end if;
    perform public._org_set_holder(p_position, p_user);
  end if;
end $$;
grant execute on function public.assign_holder(text, uuid) to authenticated;

-- ---- starting org chart (does not overwrite edits) ------------------------------
insert into public.org_positions (id, title, group_name, planned_name, role_slug, parent_id, guided_by_id, kind, sort) values
${inserts}
on conflict (id) do nothing;
${guided}

commit;

-- Verify
select (select count(*) from public.org_positions) as seats,
       (select count(*) from public.app_users where status = 'pending') as pending,
       (select string_agg(email, ', ') from public.admin_emails) as admin_emails;
`;
writeFileSync('supabase/org_approval.sql', sql, 'utf8');
